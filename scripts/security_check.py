# Rules
# ---------------------------------------------------------------------------
def check_dart_bad_cert(findings: List[Finding]) -> None:
    for path in walk(os.path.join(MOBILE, "lib")):
        if not path.endswith(".dart"):
            continue
        lines = read_lines(path)
        text = "\n".join(lines)
        if "badCertificateCallback" not in text:
            continue
        guarded = "kDebugMode" in text
        for i, line in enumerate(lines, 1):
            if "badCertificateCallback" not in line:
                continue
            window = " ".join(lines[i - 1:i + 3])
            returns_true = re.search(r"=>\s*true\b", window) is not None
            if returns_true:
                findings.append(Finding("dart-bad-cert", rel(path), i, "badCertificateCallback unconditionally returns true"))
            elif not guarded:
                findings.append(Finding("dart-bad-cert", rel(path), i, "badCertificateCallback used without a kDebugMode guard"))
        # the override must also never be installed in release builds
        if "HttpOverrides.global" in text and not re.search(r"if\s*\(\s*!\s*kDebugMode\s*\)\s*return", text):
            findings.append(Finding("dart-bad-cert", rel(path), 0, "HttpOverrides.global installed without an `if (!kDebugMode) return` guard"))


def check_android(findings: List[Finding]) -> None:
    manifest = os.path.join(MOBILE, "android", "app", "src", "main", "AndroidManifest.xml")
    for i, line in enumerate(read_lines(manifest), 1):
        if re.search(r'usesCleartextTraffic\s*=\s*"true"', line):
            findings.append(Finding("android-cleartext", rel(manifest), i, 'usesCleartextTraffic="true" in the MAIN manifest (allow it only in src/debug)'))
        if re.search(r'allowBackup\s*=\s*"true"', line):
            findings.append(Finding("android-cleartext", rel(manifest), i, 'allowBackup="true" exposes app data (token) to backups'))
        if re.search(r'debuggable\s*=\s*"true"', line):
            findings.append(Finding("android-cleartext", rel(manifest), i, 'android:debuggable="true" in the MAIN manifest'))
    text = "\n".join(read_lines(manifest))
    if text and "allowBackup" not in text:
        findings.append(Finding("android-cleartext", rel(manifest), 0, "allowBackup is not set explicitly (default is true)"))
    if text and "usesCleartextTraffic" not in text:
        findings.append(Finding("android-cleartext", rel(manifest), 0, 'set android:usesCleartextTraffic="false" explicitly'))

    gradle = os.path.join(MOBILE, "android", "app", "build.gradle.kts")
    lines = read_lines(gradle)
    in_release = False
    for i, line in enumerate(lines, 1):
        if re.search(r"\brelease\s*\{", line):
            in_release = True
        if in_release and re.search(r'signingConfig\s*=\s*signingConfigs\.getByName\(\s*"debug"\s*\)', line):
            findings.append(Finding("android-release-signing", rel(gradle), i, "release build is signed with the debug key"))
            in_release = False
        if re.search(r'applicationId\s*=\s*"com\.example\.', line):
            findings.append(Finding("android-release-signing", rel(gradle), i, "applicationId still uses the com.example.* placeholder"))


def check_python_rules(findings: List[Finding], files: List[str]) -> None:
    for path in files:
        if not path.endswith(".py") or is_test(path):
            continue
        lines = read_lines(path)
        r = rel(path)
        before = len(findings)
        for i, line in enumerate(lines, 1):
            stripped = line.strip()
            if stripped.startswith("#"):
                continue
            if re.search(r"allow_origins\s*=\s*\[\s*[\"']\*[\"']\s*\]", line):
                findings.append(Finding("cors-wildcard", r, i, 'allow_origins=["*"] hard-coded; read BACKEND_CORS_ORIGINS'))
            if re.search(r"(getenv|environ\.get)\(\s*[\"']OTP_DEV_MODE[\"']\s*,\s*[\"'](true|1|yes)[\"']", line, re.I):
                findings.append(Finding("otp-dev-default", r, i, "OTP_DEV_MODE defaults to true in code (use settings.otp_dev_mode)"))
            if re.search(r"OTP_DEV_MODE\s*[:=]\s*[\"']?(true|1)\b", line, re.I) and "config.py" not in r:
                findings.append(Finding("otp-dev-default", r, i, "OTP_DEV_MODE hard-coded to true"))
            if "weights_only=False" in line and not stripped.startswith(('"', "'", "``")) and "``" not in line:
                window = " ".join(lines[max(0, i - 4):i])
                if "_allow_unsafe_checkpoint" not in window:
                    findings.append(Finding("torch-unsafe-load", r, i, "torch.load(weights_only=False) without the explicit YOLOX_ALLOW_UNSAFE_CHECKPOINT guard"))
            if re.search(r"\btext\(\s*f[\"']", line) or re.search(r"\btext\(\s*[\"'][^\"']*[\"']\s*(%|\+|\.format)", line):
                findings.append(Finding("sql-fstring", r, i, "SQL built with an f-string / concatenation inside text(); use bound parameters"))
            if re.search(r"\.execute\(\s*f[\"']", line):
                findings.append(Finding("sql-fstring", r, i, "f-string passed to execute()"))
            if re.search(r"shell\s*=\s*True", line):
                findings.append(Finding("shell-true", r, i, "subprocess call with shell=True"))
            if re.search(r"(?<![\w.])(eval|exec)\(", line) or re.search(r"\bpickle\.loads?\(", line) or re.search(r"\byaml\.load\(", line) \
                    or "verify=False" in line or "CERT_NONE" in line or "_create_unverified_context" in line:
                findings.append(Finding("dangerous-call", r, i, "eval/exec/pickle/yaml.load/TLS verification disabled"))
        # honour inline suppressions (must name the rule; give a reason after "--")
        findings[before:] = [f for f in findings[before:] if not suppressed(lines, f.line, f.rule)]


def git_tracked_files() -> List[str]:
    try:
        out = subprocess.run(["git", "ls-files"], cwd=REPO, capture_output=True, text=True, timeout=60)
        if out.returncode == 0:
            return [l.strip() for l in out.stdout.splitlines() if l.strip()]
    except (OSError, subprocess.SubprocessError):
        pass
    return []


TRACKED_FORBIDDEN = ["*.jks", "*.keystore", "key.properties", "google-services.json", "GoogleService-Info.plist",
                     "*firebase-adminsdk*.json", "*service-account*.json", "*serviceAccount*.json",
                     "*.db", "*.sqlite", "*.sqlite3", ".env", "*/.env", ".env.*", "*/.env.*", "*.pem", "*.p12", "id_rsa", "id_ed25519"]
TRACKED_ALLOWED = ["*.env.example", ".env.example", "*/.env.example"]


def check_tracked_files(findings: List[Finding]) -> None:
    tracked = git_tracked_files()
    if not tracked:
        print("note: `git ls-files` unavailable (not a git checkout?) -- tracked-file check skipped", file=sys.stderr)
        return
    for path in tracked:
        name = path.rsplit("/", 1)[-1]
        if any(fnmatch.fnmatch(path, a) or fnmatch.fnmatch(name, a) for a in TRACKED_ALLOWED):
            continue
        if any(fnmatch.fnmatch(path, p) or fnmatch.fnmatch(name, p) for p in TRACKED_FORBIDDEN):
            findings.append(Finding("tracked-secret-file", path, 0, "secret/local-data file is committed to git"))


SECRET_PATTERNS = [
    (re.compile(r"-----BEGIN (?:RSA |EC |DSA |OPENSSH |PGP |ENCRYPTED )?PRIVATE KEY(?: BLOCK)?-----"), "private key block"),
    (re.compile(r"\bAKIA[0-9A-Z]{16}\b"), "AWS access key id"),
    (re.compile(r"\b(?:ghp|gho|ghu|ghs|ghr)_[A-Za-z0-9]{30,}\b|\bgithub_pat_[A-Za-z0-9_]{40,}\b"), "GitHub token"),
    (re.compile(r"\bxox[abprs]-[A-Za-z0-9-]{10,}\b"), "Slack token"),
    (re.compile(r"\bAIza[0-9A-Za-z_\-]{35}\b"), "Google API key"),
    (re.compile(r"\bsk_live_[0-9a-zA-Z]{20,}\b"), "Stripe live key"),
    (re.compile(r"(?i)\b(?:postgres(?:ql)?|mysql|mongodb(?:\+srv)?|redis)://[^\s:/@\"'{}$]+:[^\s@\"'{}$]{3,}@"), "database URL with embedded password"),
    # hard-coded credential literals: NAME_PASSWORD = "literal" / password: "literal" / 'password': 'literal'
    (re.compile(r"(?i)[\"']?\b\w*(?:password|passwd|secret|api[_-]?key)\w*[\"']?\s*(?::\s*[\w\[\]| .]+)?[=:]\s*[\"'](?!\s*[\"'])(?![^\"']*(?:\$\{|\{\{|<|>|%s|\.\.\.|xxx|changeme|your[-_ ]))[^\"'\s]{6,}[\"']"),
     "hard-coded password/secret literal"),
    # unquoted YAML/.env style:  POSTGRES_PASSWORD: rdms_password
    (re.compile(r"(?i)^\s*[\w.-]*(?:password|secret|api[_-]?key)[\w.-]*\s*:\s*(?![\"'$<{#\[\s])[^\s#]{4,}\s*$"),
     "hard-coded password/secret literal (YAML)"),
    # client-side comparison against a literal:  password === 'Admin@123'
    (re.compile(r"(?i)\b(?:password|passwd|pwd)\b\s*[!=]==?\s*[\"'][^\"']{4,}[\"']"),
     "hard-coded password/secret literal (comparison)"),
]
# Lines that merely define the NAME of an env var or an obviously empty/placeholder value are not secrets.
SECRET_LINE_IGNORE = re.compile(r"(?i)(getenv|environ|os\.environ|String\.fromEnvironment|process\.env|placeholder|example|hintText|labelText|obscureText|_KEY\s*=\s*[\"'](?:auth_token|rememberedEmail|custom_server_url))")


def suppressed(lines: List[str], idx: int, rule: str) -> bool:
    """`# security-check: ignore <rule> -- <reason>` on the same line or the line above silences one finding."""
    if idx < 1:
        return False
    marker = f"security-check: ignore {rule}"
    return marker in lines[idx - 1] or (idx >= 2 and marker in lines[idx - 2])


def check_secret_patterns(findings: List[Finding], files: List[str]) -> None:
    for path in files:
        if is_test(path):
            continue
        lines = read_lines(path)
        for i, line in enumerate(lines, 1):
            if len(line) > 2000:
                continue
            for pattern, label in SECRET_PATTERNS:
                if pattern.search(line):
                    if label.startswith("hard-coded") and SECRET_LINE_IGNORE.search(line):
                        continue
                    if suppressed(lines, i, "secret-pattern"):
                        continue
                    findings.append(Finding("secret-pattern", rel(path), i, label))
                    break


def check_docker_and_git(findings: List[Finding]) -> None:
    dockerfile = os.path.join(BACKEND, "Dockerfile")
    text = "\n".join(read_lines(dockerfile))
    if text and not (re.search(r"^\s*USER\s+(?!root\b)\S+", text, re.M) or "gosu" in text):
        findings.append(Finding("docker-root", rel(dockerfile), 0, "image runs as root (add a non-root USER or an entrypoint that drops privileges)"))
    ignore = "\n".join(read_lines(os.path.join(BACKEND, ".dockerignore")))
    for needed in (".env", "*.db", ".cache", "scripts/*.exe"):
        if needed not in ignore:
            findings.append(Finding("docker-root", rel(os.path.join(BACKEND, ".dockerignore")), 0, f".dockerignore does not exclude {needed}"))
    for gi, needed in ((os.path.join(MOBILE, "android", ".gitignore"), ("key.properties", "*.jks", "*.keystore")),
                       (os.path.join(BACKEND, ".gitignore"), (".env",))):
        content = "\n".join(read_lines(gi))
        for n in needed:
            if n not in content:
                findings.append(Finding("gitignore", rel(gi), 0, f"{n} is not git-ignored"))


def check_fail_closed_config(findings: List[Finding]) -> None:
    """APP_ENV must fail closed; the compose backend must declare its proxy count; registration must be gated."""
    config = os.path.join(BACKEND, "app", "core", "config.py")
    text = "\n".join(read_lines(config))
    if text and "return not self.is_development" not in text:
        findings.append(Finding("env-fail-open", rel(config), 0, "is_production must be `not is_development` (unknown APP_ENV values must be strict)"))
    fail_open = re.compile(r"APP_ENV.*==\s*[\"']production[\"']")
    for path in walk(os.path.join(BACKEND, "app")):
        if path.endswith(".py") and os.path.abspath(path) != os.path.abspath(config):
            for i, line in enumerate(read_lines(path), 1):
                if fail_open.search(line):
                    findings.append(Finding("env-fail-open", rel(path), i, "compares APP_ENV to 'production' directly (fails open for other names); use settings.is_production"))
    auth_routes = os.path.join(BACKEND, "app", "api", "v1", "routes", "auth.py")
    auth_text = chr(10).join(read_lines(auth_routes))
    register_block = auth_text.split("def register(", 1)[-1].split("@router", 1)[0] if "def register(" in auth_text else ""
    if "Depends(require_admin)" not in register_block:
        findings.append(Finding("open-registration", rel(auth_routes), 0, "POST /auth/register must depend on require_admin (there is no self-registration)"))
    compose = os.path.join(REPO, "Road-Distress-Management-System", "docker-compose.yml")
    ctext = "\n".join(read_lines(compose))
    if ctext and "TRUSTED_PROXY_COUNT" not in ctext:
        findings.append(Finding("proxy-config", rel(compose), 0, "backend service does not set TRUSTED_PROXY_COUNT (all users would share one rate-limit bucket behind nginx)"))


# ---------------------------------------------------------------------------
def deferred_reason(f: Finding) -> str:
    for (rule, pattern), why in DEFERRED.items():
        if f.rule == rule and fnmatch.fnmatch(f.path, pattern):
            return why
    return ""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--strict", action="store_true", help="treat knowingly-deferred findings as failures too")
    args = parser.parse_args()

    files = scan_files()
    findings: List[Finding] = []
    check_dart_bad_cert(findings)
    check_android(findings)
    check_python_rules(findings, files)
    check_tracked_files(findings)
    check_secret_patterns(findings, files)
    check_docker_and_git(findings)
    check_fail_closed_config(findings)

    new, deferred = [], []
    for f in findings:
        (deferred if deferred_reason(f) and not args.strict else new).append(f)

    print(f"security_check: scanned {len(files)} files under {rel(REPO) or '.'}")
    if deferred:
        print(f"\nKNOWINGLY DEFERRED ({len(deferred)}) -- allow-listed in scripts/security_check.py:")
        seen = set()
        for f in deferred:
            print(f"  - {f}")
            seen.add(deferred_reason(f))
        for why in sorted(seen):
            print(f"      why: {why}")
    if new:
        print(f"\nFAILURES ({len(new)}):")
        for f in new:
            print(f"  ! {f}")
        print("\nsecurity_check FAILED")
        return 1
    print("\nsecurity_check passed" + (" (strict)" if args.strict else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
