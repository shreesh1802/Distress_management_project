#!/usr/bin/env python3
"""
Offline security regression check for the Road Inspection project (stdlib only).

Run from anywhere:      python scripts/security_check.py
Strict (CI / release):  python scripts/security_check.py --strict     (deferred items fail too)

Exit status 0 = no new findings; 1 = at least one finding that is not in DEFERRED below.

What it looks for (each rule maps to a finding of the security audit):
  dart-bad-cert           badCertificateCallback that can return true outside a kDebugMode guard   (ATK-007)
  android-cleartext       usesCleartextTraffic="true" / allowBackup="true" / debuggable in MAIN manifest (ATK-011)
  android-release-signing release build signed with the debug key; com.example application id      (ATK-011)
  cors-wildcard           allow_origins=["*"] hard-coded in Python                                  (ATK-015)
  otp-dev-default         OTP_DEV_MODE defaulting to true in code                                   (ATK-003)
  torch-unsafe-load       weights_only=False without the explicit YOLOX_ALLOW_UNSAFE_CHECKPOINT guard (ATK-024)
  sql-fstring             f-string / concatenated SQL passed to text()                              (SQL injection)
  shell-true              subprocess with shell=True                                                (command injection)
  dangerous-call          eval/exec/pickle.load/yaml.load/verify=False/CERT_NONE
  tracked-secret-file     .env / *.db / *.jks / key.properties / google-services.json in `git ls-files`
  secret-pattern          private key blocks, AWS/GitHub/Slack/Google keys, hard-coded password literals
  docker-root             Dockerfile without a non-root user; .dockerignore missing secrets
  gitignore               .gitignore files missing the secret patterns
  env-fail-open           APP_ENV handling that fails open / registration gate missing / compose without TRUSTED_PROXY_COUNT

Knowingly deferred items live in DEFERRED with a justification, so they stay visible in every run.
"""

import argparse
import fnmatch
import os
import re
import subprocess
import sys
from typing import Dict, Iterable, List, Tuple

REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
BACKEND = os.path.join(REPO, "Road-Distress-Management-System", "backend")
MOBILE = os.path.join(REPO, "mobile")

SKIP_DIRS = {
    ".git", ".venv", "venv", "node_modules", "build", ".dart_tool", ".gradle", "__pycache__", ".cache",
    "uploads", "models", "SECURITY_REPORTS", ".pytest_cache", "ephemeral", "Pods",
}
THIS_FILE = os.path.abspath(__file__)

# ---------------------------------------------------------------------------
# Knowingly deferred items: (rule, relative path glob) -> justification.
# Remove an entry as soon as the underlying issue is fixed; --strict ignores this list.
# ---------------------------------------------------------------------------
DEFERRED: Dict[Tuple[str, str], str] = {
    ("android-release-signing", "mobile/android/app/build.gradle.kts"):
        "OWNER DECISION: needs the Play upload keystore (key.properties, kept outside git). "
        "See SECURITY.md 'Play Store pre-submission checklist'.",
    ("tracked-secret-file", "mobile/android/app/google-services.json"):
        "Firebase CLIENT configuration (project and app identifiers, public API key). It is public by design: the key is "
        "restricted by package name + SHA fingerprints and protected by Firebase rules. The service-account key is the "
        "secret; it is never committed (see the service-account patterns) and lives in FIREBASE_CREDENTIALS_JSON.",
    ("secret-pattern", "mobile/android/app/google-services.json"):
        "Firebase client API key, public by design (see above).",
    ("secret-pattern", "mobile/lib/firebase_options.dart"):
        "Firebase client API keys generated by `flutterfire configure`, public by design (see above).",
    ("secret-pattern", "Road-Distress-Management-System/docker-compose.yml"):
        "Local docker-compose demo database credentials. Replace with real secrets (compose secrets / env file) "
        "before any internet-facing deployment; not used by the Railway deployment.",
    ("secret-pattern", "Road-Distress-Management-System/frontend/*"):
        "Legacy React app with hard-coded mock credentials (ATK-026). OWNER DECISION: delete or archive the app; "
        "nothing deployed serves it.",
}

# Files whose content is scanned (by extension).
CODE_EXT = {".py", ".dart", ".kts", ".gradle", ".yml", ".yaml", ".xml", ".json", ".conf", ".sh", ".ts", ".tsx", ".js", ".properties"}
TEST_PATH = re.compile(r"(^|/)(tests?|test_data)(/|$)|(^|/)test_[^/]*\.py$|_test\.dart$|\.test\.(ts|tsx|js)$")


class Finding:
    def __init__(self, rule: str, path: str, line: int, message: str):
        self.rule, self.path, self.line, self.message = rule, path, line, message

    def key(self) -> str:
        return f"{self.rule} {self.path}:{self.line}"

    def __str__(self) -> str:
        loc = f"{self.path}:{self.line}" if self.line else self.path
        return f"[{self.rule}] {loc}  {self.message}"


def rel(path: str) -> str:
    return os.path.relpath(path, REPO).replace("\\", "/")


def walk(root: str) -> Iterable[str]:
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
        for name in filenames:
            full = os.path.join(dirpath, name)
            if os.path.abspath(full) == THIS_FILE:
                continue
            yield full


def read_lines(path: str) -> List[str]:
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as fh:
            return fh.read().splitlines()
    except OSError:
        return []


def is_test(path: str) -> bool:
    return bool(TEST_PATH.search(rel(path)))


def scan_files() -> List[str]:
    files = []
    for root in (BACKEND, MOBILE, os.path.join(REPO, "Road-Distress-Management-System", "nginx"),
                 os.path.join(REPO, "Road-Distress-Management-System", "frontend"), os.path.join(REPO, "scripts")):
        if os.path.isdir(root):
            files.extend(p for p in walk(root) if os.path.splitext(p)[1].lower() in CODE_EXT)
    for extra in ("docker-compose.yml",):
        full = os.path.join(REPO, "Road-Distress-Management-System", extra)
        if os.path.isfile(full):
            files.append(full)
    return sorted(set(files))


